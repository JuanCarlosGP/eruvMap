import type { Geometry } from 'geojson'
import type { ContributeFormValues } from '../types/contribute'
import { geometryCenter } from './geometry'

export type ContributeDrawTool = 'polygon' | 'line' | 'point'

export function inferGeometryMeta(geometry: Geometry | null) {
  if (!geometry) {
    return {
      geometry_kind: 'perimeter' as const,
      geometry_precision: 'exact' as const,
      note: '',
    }
  }
  if (geometry.type === 'Point') {
    return {
      geometry_kind: 'point' as const,
      geometry_precision: 'approximate' as const,
      note:
        'Representative point proposed via eruvMap contribution tool; not a verified boundary.',
    }
  }
  if (geometry.type === 'LineString') {
    return {
      geometry_kind: 'perimeter' as const,
      geometry_precision: 'exact' as const,
      note:
        'Partial segment proposed via eruvMap contribution tool; not the full perimeter.',
    }
  }
  return {
    geometry_kind: 'perimeter' as const,
    geometry_precision: 'exact' as const,
    note: 'Perimeter proposed via eruvMap contribution tool; pending maintainer review.',
  }
}

export function buildContributionFeature(
  form: ContributeFormValues,
  geometry: Geometry,
) {
  const meta = inferGeometryMeta(geometry)
  const slug = form.name_en
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 48)
  const id = `proposal-${slug || 'eruv'}-${Date.now()}`

  return {
    type: 'Feature',
    id,
    properties: {
      id,
      name_en: form.name_en.trim(),
      name_he: form.name_he.trim() || null,
      city: form.city.trim(),
      country: form.country.trim(),
      geometry_kind: meta.geometry_kind,
      status: 'unknown',
      source: form.source_url.trim(),
      source_url: form.source_url.trim(),
      license: 'Community proposal — pending review (see source_url)',
      verified_at: new Date().toISOString().slice(0, 10),
      contact_url: form.contact_url.trim() || null,
      geometry_precision: meta.geometry_precision,
      note: meta.note,
    },
    geometry,
  }
}

export function featureGeometryJson(geometry: Geometry): string {
  return JSON.stringify(geometry, null, 2)
}

export function downloadProposalGeoJson(
  feature: ReturnType<typeof buildContributionFeature>,
) {
  const collection = {
    type: 'FeatureCollection',
    attribution:
      'Proposal generated by eruvMap (not yet merged). If geometry derives from OpenStreetMap, © OpenStreetMap contributors ODbL 1.0.',
    features: [feature],
  }
  const blob = new Blob([JSON.stringify(collection, null, 2)], {
    type: 'application/geo+json',
  })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `${feature.properties.id}.geojson`
  a.click()
  URL.revokeObjectURL(url)
}

export function referencePointForGeometry(
  geometry: Geometry | null,
): [number, number] | null {
  if (!geometry) return null
  return geometryCenter({ type: 'Feature', properties: {}, geometry })
}
